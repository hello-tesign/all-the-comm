const { chromium } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1,reducedMotion:'no-preference'});
  let blockedWrites=0;
  await context.route('**/*',route=>['GET','HEAD','OPTIONS'].includes(route.request().method())?route.continue():(blockedWrites++,route.abort()));
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  await page.goto('http://127.0.0.1:4173/team/',{waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.documentElement.classList.contains('isos-motion-enabled'));
  await page.locator('.discipline-stage').evaluate(el=>scrollTo({top:scrollY+el.getBoundingClientRect().top-155,behavior:'instant'}));
  await page.waitForTimeout(1500);
  await page.locator('.discipline-nav button').nth(6).click();
  await page.waitForTimeout(220);
  const opacity=await page.locator('.discipline-panel:not([hidden]) .discipline-copy').evaluate(el=>[...el.children].map(x=>({text:x.textContent.replace(/\s+/g,' ').trim(),opacity:getComputedStyle(x).opacity,transform:getComputedStyle(x).transform,visibility:getComputedStyle(x).visibility})));
  await page.screenshot({path:path.join(__dirname,'team-switch-220ms-fixed.png')});
  const result={generated:new Date().toISOString(),url:page.url(),viewport:[1440,1000],opacity,allCopyVisible:opacity.every(x=>Number(x.opacity)===1&&x.visibility==='visible'),errors,blockedWrites};
  await page.goto('http://127.0.0.1:4173/works/',{waitUntil:'networkidle'});
  await page.locator('#services').evaluate(el=>scrollTo({top:scrollY+el.getBoundingClientRect().top-110,behavior:'instant'}));
  await page.waitForTimeout(1500);
  result.serviceTabs=await page.locator('.works-capabilities [role=tab]').evaluateAll(els=>els.map(el=>({text:el.textContent.trim(),top:el.getBoundingClientRect().top,left:el.getBoundingClientRect().left,width:el.getBoundingClientRect().width})));
  await page.screenshot({path:path.join(__dirname,'works-service-tabs-fixed.png')});
  await page.goto('http://127.0.0.1:4173/contact/',{waitUntil:'networkidle'});
  await page.locator('input[name=attachments]').evaluate(el=>{const field=el.closest('.field');scrollTo({top:scrollY+field.getBoundingClientRect().top-250,behavior:'instant'});});
  await page.waitForTimeout(700);
  result.fileField=await page.locator('input[name=attachments]').evaluate(el=>({text:el.closest('.field').innerText,nativeComputed:{width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height,opacity:getComputedStyle(el).opacity}}));
  await page.screenshot({path:path.join(__dirname,'contact-attachment-fixed.png')});
  result.errors=errors;result.blockedWrites=blockedWrites;
  await fs.writeFile(path.join(__dirname,'team-recheck.json'),JSON.stringify(result,null,2));
  await browser.close();console.log(JSON.stringify(result));
})().catch(e=>{console.error(e);process.exitCode=1});
